// Helper to gather all PDFs across all batches
export const getAllNotesAndPdfs = (): NotePdf[] => {
  const notes: NotePdf[] = [];
  BATCHES_DATA.forEach(batch => {
    batch.subjects.forEach(subject => {
      subject.chapters.forEach(chapter => {
        if (chapter.notes) {
          notes.push(...chapter.notes);
        }
      });
    });
  });
  return notes;
};
